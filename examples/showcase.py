"""Figures used in the README.

Two pictures, both drawn from code that ships with the repository:

- the four fracture shapes of the paper, from ``fracture_surface_function``;
- the worked-example trace stored in ``examples/example_reference.npz``.

Run from the repository root::

    python examples/showcase.py

The pictures are written to ``docs/images/``. They are the only figures kept
in git. Every other plot is regenerated by the scripts in ``tools/``.
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from mpl_toolkits.mplot3d import Axes3D  # noqa: F401

_REPO = Path(__file__).resolve().parents[1]
if str(_REPO) not in sys.path:
    sys.path.insert(0, str(_REPO))

from rahpo.fracture import fracture_surface_function
from rahpo.parameters import GeometryParams

OUT = _REPO / "docs" / "images"
SHAPES = (
    ("planar", "Planar"),
    ("planar-tilted", "Inclined, 8°"),
    ("piecewise_yz", "Piecewise concave"),
    ("sinusoidal_3d", "Biaxial corrugation"),
)


def _surface(kind: str, n: int = 81) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return absolute (x, y, z) of one fracture shape on the paper's window."""
    geom = GeometryParams(fracture_type=kind, ymin=1.0, ymax=9.0, zmin=1.0, zmax=9.0, amplitude=0.25)
    local_y = np.linspace(0.0, geom.ymax - geom.ymin, n)
    local_z = np.linspace(0.0, geom.zmax - geom.zmin, n)
    y, z = np.meshgrid(local_y, local_z, indexing="ij")
    x = fracture_surface_function(y, z, geom)
    return x, y + geom.ymin, z + geom.zmin


def fracture_shapes(path: Path) -> None:
    """Draw the four fracture shapes used in the paper."""
    fig = plt.figure(figsize=(8.2, 7.2))
    for i, (kind, title) in enumerate(SHAPES, start=1):
        ax = fig.add_subplot(2, 2, i, projection="3d")
        x, y, z = _surface(kind)
        ax.plot_surface(x, y, z, color="#2c6fbb", rstride=4, cstride=4,
                        linewidth=0.15, edgecolor="white", antialiased=True, shade=False)
        ax.set_title(title, fontsize=11, pad=2)
        ax.set_xlabel("x (m)", fontsize=8, labelpad=2)
        ax.set_ylabel("y (m)", fontsize=8, labelpad=2)
        ax.set_zlabel("z (m)", fontsize=8, labelpad=2)
        ax.tick_params(labelsize=7, pad=0)
        ax.view_init(elev=22, azim=-62)
        ax.set_xlim(2.0, 8.5)
        ax.set_ylim(1, 9)
        ax.set_zlim(1, 9)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def example_trace(path: Path) -> None:
    """Plot the shipped trace of the 1 m by 1 m planar fracture."""
    data = np.load(_REPO / "examples" / "example_reference.npz")
    time_ns = data["time_ns"]
    amplitude = data["amplitude"]
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    ax.plot(time_ns, amplitude, color="#9b1d20", lw=1.2)
    ax.set_xlim(110, 170)
    ax.set_xlabel("Time (ns)")
    ax.set_ylabel(r"Scattered $E_z$ (V/m)")
    ax.set_title("Worked example: 1 m × 1 m planar fracture")
    ax.grid(True, ls="--", lw=0.4, alpha=0.7)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    fracture_shapes(OUT / "fracture_shapes.png")
    example_trace(OUT / "example_trace.png")
    print(f"wrote {OUT / 'fracture_shapes.png'}")
    print(f"wrote {OUT / 'example_trace.png'}")


if __name__ == "__main__":
    main()
